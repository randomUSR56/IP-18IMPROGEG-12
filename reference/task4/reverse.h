#ifndef REVERSE_H
#define REVERSE_H

/*
 * Task 4 - reverse a string IN PLACE.
 *
 * The characters of `str` are rearranged inside the very same memory area the
 * caller passed in; nothing is allocated and nothing is returned.
 *
 * `str` must point to a writable, '\0'-terminated array (NOT a string literal,
 * which lives in read-only memory). NULL is ignored.
 */
void reverse(char *str);

#endif
